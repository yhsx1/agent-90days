# 输入两个整数
num_1 = int(input("请输入第一个整数："))
num_2 = int(input("请输入第二个整数："))

# 输出其中计算结果
print("==== 计算结果 ====")
print(f"加法：{num_1 + num_2}")
print(f"减法：{num_1 - num_2}")
print(f"乘法：{num_1 * num_2}")
print(f"除法：{num_1 / num_2:.2f}")
print(f"整除：{num_1 // num_2}")
print(f"取余：{num_1 % num_2}")
print(f"幂运算：{num_1 ** num_2}")
print("==================")